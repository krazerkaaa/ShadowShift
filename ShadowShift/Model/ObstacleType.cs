namespace ShadowShift.Model
{
    // Типы объектов, которые могут встречаться на уровне
    public enum ObstacleType
    {
        Spike,          // Нижний шип: всегда смертелен, нужно перепрыгивать
        CeilingSpike,   // Потолочный шип: висит сверху и ограничивает высоту прыжка
        PhaseBarrier,   // Фазовый барьер: пропускает игрока только в совпадающей фазе
        SpeedPortal     // Портал скорости: меняет множитель скорости бега
    }
}